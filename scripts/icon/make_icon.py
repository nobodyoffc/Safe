#!/usr/bin/env python3
"""Safe's app icon for Android, iOS and macOS, from one source.

The 密签 logo (logo.png, black chrome, transparent) is recoloured to pale gold by
mapping its brightness onto a gold ramp, so its own bevels and shine survive.
It sits on a near-black face with a gold combination-lock dial.

Needs Pillow, numpy and rsvg-convert (brew install librsvg).

    python3 scripts/icon/make_icon.py [--ios ~/iosapp/safeforios] [--mac ~/MacApp/SafeForMac]

Without flags it only writes the Android resources.
"""
import argparse, math, os, subprocess, tempfile
import numpy as np
from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
ANDROID = os.path.join(HERE, "..", "..", "app", "src", "main")
C = 54            # centre of the 108-unit adaptive-icon canvas
LOGO_H = 48.0     # logo height, inside the 66-unit safe circle
BG_IN, BG_OUT, INK = "#1A2233", "#030509", "#E3CC94"
GOLD = [(0.00, (0x6E, 0x58, 0x30)), (0.10, (0x9C, 0x83, 0x52)), (0.35, (0xCF, 0xB7, 0x82)),
        (0.65, (0xE8, 0xD6, 0xA8)), (0.90, (0xFA, 0xF1, 0xD8)), (1.00, (0xFF, 0xFB, 0xF0))]


def gold_logo(tmp):
    im = Image.open(os.path.join(HERE, "logo.png")).convert("RGBA")
    im = im.crop(im.getbbox())
    a = np.asarray(im).astype(np.float32) / 255
    lum = 0.299 * a[..., 0] + 0.587 * a[..., 1] + 0.114 * a[..., 2]
    xs = [s[0] for s in GOLD]
    rgb = np.dstack([np.interp(lum, xs, [s[1][c] for s in GOLD]) for c in range(3)])
    out = Image.fromarray(np.dstack([rgb, a[..., 3] * 255]).astype(np.uint8), "RGBA")
    path = os.path.join(tmp, "logo_gold.png")
    out.save(path)
    return out, path


def ticks():
    for i in range(48):
        t = 2 * math.pi * i / 48
        r1, r2 = 31.2, (34.2 if i % 4 == 0 else 33.2)
        yield C + r1 * math.sin(t), C - r1 * math.cos(t), C + r2 * math.sin(t), C - r2 * math.cos(t), i % 4 == 0


def svg(logo, logo_path, shape, view="18 18 72 72"):
    """shape: 'rect' (rounded tile), 'circle', or 'full' (square, full bleed)."""
    w, h = logo.size
    lw = LOGO_H * w / h
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="{view}">',
         f'<defs><radialGradient id="bg" cx="54" cy="44" r="52" gradientUnits="userSpaceOnUse">'
         f'<stop offset="0" stop-color="{BG_IN}"/><stop offset="1" stop-color="{BG_OUT}"/></radialGradient></defs>',
         {"rect": '<rect x="18" y="18" width="72" height="72" rx="16" fill="url(#bg)"/>',
          "circle": '<circle cx="54" cy="54" r="36" fill="url(#bg)"/>',
          "full": '<rect width="108" height="108" fill="url(#bg)"/>'}[shape],
         f'<circle cx="54" cy="54" r="29.6" fill="none" stroke="{INK}" stroke-opacity="0.14" stroke-width="0.8"/>']
    for x1, y1, x2, y2, big in ticks():
        o.append(f'<line x1="{x1:.2f}" y1="{y1:.2f}" x2="{x2:.2f}" y2="{y2:.2f}" stroke="{INK}" '
                 f'stroke-opacity="{0.55 if big else 0.22}" stroke-width="{0.9 if big else 0.6}" stroke-linecap="round"/>')
    o.append(f'<image x="{C - lw / 2:.2f}" y="{C - LOGO_H / 2:.2f}" width="{lw:.2f}" height="{LOGO_H:.2f}" xlink:href="{logo_path}"/>')
    o.append("</svg>")
    return "\n".join(o)


def render(tmp, name, text, size):
    src, out = os.path.join(tmp, name + ".svg"), os.path.join(tmp, f"{name}_{size}.png")
    open(src, "w").write(text)
    subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), src, "-o", out], check=True)
    return out


def background_xml():
    seg = lambda big: " ".join(f"M{a:.2f},{b:.2f} L{c:.2f},{d:.2f}" for a, b, c, d, g in ticks() if g == big)
    ink = INK[1:]
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/icon/make_icon.py: near-black face with a gold combination-lock dial. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0 L108,0 L108,108 L0,108 Z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="54" android:centerY="44" android:gradientRadius="52">
                <item android:offset="0" android:color="#FF{BG_IN[1:]}" />
                <item android:offset="1" android:color="#FF{BG_OUT[1:]}" />
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="M54,24.4 A29.6,29.6 0 1,1 53.99,24.4 Z" android:strokeColor="#24{ink}" android:strokeWidth="0.8" />
    <path android:pathData="{seg(False)}" android:strokeColor="#38{ink}" android:strokeWidth="0.6" android:strokeLineCap="round" />
    <path android:pathData="{seg(True)}" android:strokeColor="#8C{ink}" android:strokeWidth="0.9" android:strokeLineCap="round" />
</vector>
'''


def android(tmp, logo, logo_path):
    res = os.path.join(ANDROID, "res")
    w, h = logo.size
    for d, s, px in [("mdpi", 1, 48), ("hdpi", 1.5, 72), ("xhdpi", 2, 96), ("xxhdpi", 3, 144), ("xxxhdpi", 4, 192)]:
        n, lh = round(108 * s), round(LOGO_H * s)
        lw = round(lh * w / h)
        fg = Image.new("RGBA", (n, n), (0, 0, 0, 0))
        fg.paste(logo.resize((lw, lh), Image.LANCZOS), ((n - lw) // 2, (n - lh) // 2))
        fg.save(f"{res}/mipmap-{d}/ic_launcher_foreground.png", optimize=True)
        mono = Image.new("RGBA", (n, n), (255, 255, 255, 0))
        mono.putalpha(fg.getchannel("A"))
        mono.save(f"{res}/mipmap-{d}/ic_launcher_monochrome.png", optimize=True)
        for name, shape in [("ic_launcher", "rect"), ("ic_launcher_round", "circle")]:
            Image.open(render(tmp, shape, svg(logo, logo_path, shape), px)).save(f"{res}/mipmap-{d}/{name}.png", optimize=True)
    open(f"{res}/drawable/ic_launcher_background.xml", "w").write(background_xml())
    Image.open(render(tmp, "play", svg(logo, logo_path, "full", "0 0 108 108"), 512)).save(
        os.path.join(ANDROID, "ic_launcher-playstore.png"), optimize=True)


def ios(tmp, logo, logo_path, repo):
    # App Store icons are opaque full-bleed squares; iOS applies its own mask.
    im = Image.open(render(tmp, "ios", svg(logo, logo_path, "full"), 1024)).convert("RGB")
    im.save(os.path.join(repo, "Safe", "Assets.xcassets", "AppIcon.appiconset", "AppIcon.png"), optimize=True)


def mac(tmp, logo, logo_path, repo):
    # macOS grid: 824px rounded tile inside 1024, with a soft drop shadow.
    tile = Image.open(render(tmp, "mac", svg(logo, logo_path, "rect"), 824)).convert("RGBA")
    canvas = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))
    shadow = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))
    shadow.paste((0, 0, 0, 90), (100, 112), tile.getchannel("A"))
    canvas = Image.alpha_composite(canvas, shadow.filter(ImageFilter.GaussianBlur(12)))
    canvas.alpha_composite(tile, (100, 100))
    icons = os.path.join(repo, "app-desktop", "icons")
    canvas.save(os.path.join(icons, "icon_1024.png"), optimize=True)
    iconset = os.path.join(tmp, "Safe.iconset")
    os.makedirs(iconset, exist_ok=True)
    for s in [16, 32, 128, 256, 512]:
        canvas.resize((s, s), Image.LANCZOS).save(f"{iconset}/icon_{s}x{s}.png")
        canvas.resize((2 * s, 2 * s), Image.LANCZOS).save(f"{iconset}/icon_{s}x{s}@2x.png")
    subprocess.run(["iconutil", "-c", "icns", iconset, "-o", os.path.join(icons, "Safe.icns")], check=True)


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--ios", help="path to the iOS Safe repo")
    p.add_argument("--mac", help="path to the macOS Safe repo")
    args = p.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        logo, logo_path = gold_logo(tmp)
        android(tmp, logo, logo_path)
        if args.ios: ios(tmp, logo, logo_path, os.path.expanduser(args.ios))
        if args.mac: mac(tmp, logo, logo_path, os.path.expanduser(args.mac))
